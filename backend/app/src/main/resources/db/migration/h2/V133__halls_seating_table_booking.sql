CREATE TABLE venue_seating_rules (
    venue_id BIGINT PRIMARY KEY REFERENCES venues(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL DEFAULT 0,
    use_plan BOOLEAN NOT NULL DEFAULT FALSE,
    guest_table_choice BOOLEAN NOT NULL DEFAULT FALSE,
    limit_duration BOOLEAN NOT NULL DEFAULT FALSE,
    duration_minutes INT NOT NULL DEFAULT 120 CHECK (duration_minutes BETWEEN 15 AND 1440),
    buffer_minutes INT NOT NULL DEFAULT 0 CHECK (buffer_minutes BETWEEN 0 AND 240)
);
INSERT INTO venue_seating_rules(venue_id) SELECT id FROM venues;
