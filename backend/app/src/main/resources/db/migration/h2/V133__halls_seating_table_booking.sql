CREATE TABLE table_seatings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    table_id BIGINT NOT NULL REFERENCES venue_tables(id) ON DELETE RESTRICT,
    visit_id BIGINT NOT NULL REFERENCES visits(id) ON DELETE RESTRICT,
    booking_id BIGINT REFERENCES bookings(id) ON DELETE RESTRICT,
    table_session_id BIGINT NOT NULL REFERENCES table_sessions(id) ON DELETE RESTRICT,
    party_size INT NOT NULL CHECK (party_size > 0),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    agreed_end_at TIMESTAMP WITH TIME ZONE,
    duration_minutes INT,
    buffer_minutes INT NOT NULL DEFAULT 0,
    released_at TIMESTAMP WITH TIME ZONE,
    created_by_user_id BIGINT NOT NULL REFERENCES users(telegram_user_id) ON DELETE RESTRICT,
    revision BIGINT NOT NULL DEFAULT 0,
    UNIQUE(booking_id),
    UNIQUE(table_session_id)
);
CREATE INDEX table_seatings_current ON table_seatings(venue_id, table_id, released_at);
CREATE TABLE table_seating_moves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seating_id BIGINT NOT NULL REFERENCES table_seatings(id) ON DELETE RESTRICT,
    from_table_id BIGINT NOT NULL REFERENCES venue_tables(id) ON DELETE RESTRICT,
    to_table_id BIGINT NOT NULL REFERENCES venue_tables(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES users(telegram_user_id) ON DELETE RESTRICT,
    moved_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE seating_operations (
    venue_id BIGINT NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    actor_user_id BIGINT NOT NULL REFERENCES users(telegram_user_id) ON DELETE RESTRICT,
    request_id VARCHAR(36) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    result_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(venue_id, actor_user_id, request_id)
);
